// The token radar's model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and adds every pre-token protocol below the floor that the house's
// own watchlist rule would keep (see isRankable): the early rows the radar
// exists to find. A protocol is pre-token when its record carries no token
// (no market cap, no CoinGecko id, no symbol); live-token protocols are kept
// apart and shown with the market's own values, never mixed into the ranking.
//
// Implied value follows only from the snapshot's own figures, in four steps:
//
//   1. comps    The market's own price for a category: the median mcap/TVL
//               ratio of the live-token protocols in the same category
//               (at least 3 of them), else the median across every live-token
//               protocol in the snapshot. Clamped to [0.05, 1.00], so no
//               category's multiple can run away on a thin sample.
//   2. base     = tvl_usd x comps
//   3. growth   = 1 + clamp(change_7d, -40, +60) / 100 x 0.5
//   4. maturity = 0.70 + min(age_days, 730) / 730 x 0.30
//               (age_days unknown: 365 — the middle of the range)
//   5. breadth  = 1 + min(chains - 1, 9) x 0.02
//   implied   = max(1, round(base x growth x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the dashboard shows each row's four factors so the arithmetic is checkable.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

